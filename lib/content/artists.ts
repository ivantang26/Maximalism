const worksById = new Map(artists.flatMap((a) => a.works.map((w) => [w.id, { work: w, artist: a }] as const)));

export function getWork(id: string) {
  const entry = worksById.get(id);
  if (!entry) throw new Error(`Unknown work: ${id}`);
  return entry;
}

export function artistsInRoom(room: number) {
  return artists.filter((a) => a.room === room);
}
